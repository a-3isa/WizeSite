"""Generate lib/core/sync/schema.dart (PowerSync client schema) from server/migrations/*.sql.

Run from the repo root after changing a migration:  python server/tools/gen_client_schema.py
Only tables in the `powersync` publication are emitted. Keys that the sync rules alias as `id`
are dropped (PowerSync adds `id` implicitly). The server-side sync_rules.yaml decides which
columns each alias query selects; this mirrors them.
"""
import io
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MIGRATIONS = sorted((ROOT / 'server' / 'migrations').glob('*.sql'))
OUT = ROOT / 'lib' / 'core' / 'sync' / 'schema.dart'

# table -> key column the sync rules alias as `id` (and therefore not a separate client column)
ALIASED_KEYS = {
    'user_profiles': 'uid',
    'subscriptions': 'workspace_id',
    'project_metrics': 'project_id',
    'workspace_metrics': 'workspace_id',
}
# Columns the alias queries in sync_rules.yaml leave out.
EXCLUDED = {
    'user_profiles': {'legacy'},
    'subscriptions': {'legacy'},
}


def up_section(sql: str) -> str:
    return sql.split('-- Down Migration')[0]


def dart_type(sql_type: str) -> str:
    t = sql_type.upper()
    if t.startswith(('NUMERIC', 'REAL', 'DOUBLE')):
        return 'real'
    if t.startswith(('INTEGER', 'BIGINT', 'SMALLINT', 'BOOLEAN')):
        return 'integer'
    return 'text'  # TEXT, TIMESTAMPTZ (ISO-8601), JSONB (JSON text)


tables: dict[str, list[tuple[str, str]]] = {}
published: list[str] = []
for path in MIGRATIONS:
    sql = up_section(io.open(path, encoding='utf-8').read())
    for m in re.finditer(r'CREATE TABLE (\w+) \((.*?)\n\);', sql, re.S):
        name, body = m.group(1), m.group(2)
        cols = []
        for line in body.split('\n'):
            line = line.split('--')[0].strip().rstrip(',')
            cm = re.match(r'^([a-z_]+)\s+([A-Z]+(?:\(\d+(?:,\s*\d+)?\))?)', line)
            if not cm or cm.group(1) in ('unique', 'primary', 'check', 'constraint'):
                continue
            cols.append((cm.group(1), dart_type(cm.group(2))))
        tables[name] = cols
    pm = re.search(r'CREATE PUBLICATION powersync FOR TABLE(.*?);', sql, re.S)
    if pm:
        published = [t.strip() for t in pm.group(1).replace('\n', ' ').split(',') if t.strip()]

assert published, 'publication not found'
lines = [
    '// GENERATED by server/tools/gen_client_schema.py from server/migrations/*.sql.',
    '// Do not edit by hand; re-run the generator after changing a migration.',
    '//',
    '// Local SQLite schema for PowerSync (spec 004). Mirrors the synced server tables;',
    '// `id` is implicit. Money = real, timestamps = ISO-8601 text, JSON = text,',
    '// booleans = integer (0/1).',
    "import 'package:powersync/powersync.dart';",
    '',
    'const syncSchema = Schema([',
]
for name in published:
    cols = [
        (c, t) for c, t in tables[name]
        if c != 'id' and c != ALIASED_KEYS.get(name) and c not in EXCLUDED.get(name, set())
    ]
    lines.append(f"  Table('{name}', [")
    for c, t in cols:
        lines.append(f"    Column.{t}('{c}'),")
    lines.append('  ]),')
lines.append(']);')
OUT.parent.mkdir(parents=True, exist_ok=True)
io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(f'wrote {OUT.relative_to(ROOT)}: {len(published)} tables')
